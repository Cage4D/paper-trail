/**
 * Generates packages/contracts/test/vectors/digest-vectors.json: the signed-action
 * digest (spec §4.4) for every PaperTrail action, computed INDEPENDENTLY of Solidity
 * with viem's ABI encoder. Foundry (test/DigestVectors.t.sol) checks PaperTrailLib
 * against this file, and packages/core (Phase 3) must reproduce it byte for byte.
 *
 *   digest      = keccak256(abi.encode(DOMAIN, chainId, contract, uint8(action), signer, nonce, payloadHash))
 *   DOMAIN      = keccak256("PaperTrail.v1")
 *   payloadHash = keccak256(abi.encode(<action fields in calldata order>))
 *
 * Deterministic: fixed inputs, no randomness. Run: pnpm vectors
 */
import { writeFileSync } from "node:fs";
import { encodeAbiParameters, keccak256, toHex, type Hex } from "viem";

const OUT = new URL("../../packages/contracts/test/vectors/digest-vectors.json", import.meta.url);
const h = (s: string) => keccak256(toHex(s));
const DOMAIN = h("PaperTrail.v1");
const CHAIN_ID = 9800n;
const CONTRACT = "0x1111111111111111111111111111111111111111";
const NONCE = 7n;
const BOARD = "0x156e64214f91CE029959325013f2226f095A139B";
const EX = ["0x4f15E68607A43Ebc768AE31c6aA91Cd45C18964C", "0x34ac75a84260eefF102B3265C3bA22438b4ab031", "0x6EbE029DF8Ab7aF80B37164191658b11d3E36E80"] as const;
const ACTION = { CreateExam: 0, SetCentre: 1, RotateEpoch: 2, Release: 3, SubmitScript: 4, PublishMarks: 5, BindIdentity: 6 } as const;

const enc = (types: string[], values: unknown[]) =>
  encodeAbiParameters(types.map((type) => ({ type })), values as never);
const digest = (action: number, signer: string, payloadHash: Hex) =>
  keccak256(enc(["bytes32", "uint256", "address", "uint8", "address", "uint256", "bytes32"], [DOMAIN, CHAIN_ID, CONTRACT, action, signer, NONCE, payloadHash]));

const examId = h("vector:exam");
const centreId = h("vector:centre-A");
const v: Record<string, Record<string, unknown>> = {};
function add(name: keyof typeof ACTION, signer: string, fields: Record<string, unknown>, types: string[]) {
  const payloadHash = keccak256(enc(types, Object.values(fields)));
  v[name] = { action: ACTION[name], signer, fields, payloadHash, digest: digest(ACTION[name], signer, payloadHash) };
}

add("CreateExam", BOARD, { examId, board: BOARD, examiners: [...EX], startTime: 1_800_003_600, masterCommitment: h("vector:master"), committeeBundleHash: h("vector:bundle") },
  ["bytes32", "address", "address[3]", "uint64", "bytes32", "bytes32"]);
add("SetCentre", BOARD, { examId, centreId, commitment: h("vector:commitment"), cipherHash: h("vector:cipher") },
  ["bytes32", "bytes32", "bytes32", "bytes32"]);
add("RotateEpoch", BOARD, { centreId, board: BOARD, epoch: 3, membersHash: h("vector:members"), envelopeHash: h("vector:envelope") },
  ["bytes32", "address", "uint64", "bytes32", "bytes32"]);
add("Release", EX[0], { examId, centreId, blobHash: h("vector:blob"), examiner: EX[0] },
  ["bytes32", "bytes32", "bytes32", "address"]);
add("SubmitScript", BOARD, { examId, centreId, pseudonymHash: h("vector:pseudonym"), scriptHash: h("vector:script"), markerEpoch: 2 },
  ["bytes32", "bytes32", "bytes32", "bytes32", "uint64"]);
add("PublishMarks", BOARD, { examId, merkleRoot: h("vector:root") }, ["bytes32", "bytes32"]);
add("BindIdentity", EX[1], { role: EX[1], statementHash: h("vector:statement") }, ["address", "bytes32"]);

const file = {
  description: "PaperTrail signed-action digest vectors (spec 4.4). Generated by scripts/vectors/gen-digest-vectors.ts (viem); checked by packages/contracts/test/DigestVectors.t.sol. Sign `digest` (32 bytes) with ML-DSA-87, pure mode, empty context.",
  domain: DOMAIN, chainId: Number(CHAIN_ID), contract: CONTRACT, nonce: Number(NONCE),
  vectors: v,
};
writeFileSync(OUT, JSON.stringify(file, null, 2) + "\n");
console.log(`wrote ${Object.keys(v).length} vectors; CreateExam digest ${v.CreateExam.digest}`);
