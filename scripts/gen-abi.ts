/**
 * pnpm abi — write packages/shared/src/abi.ts from the Foundry artifact, so the API and the
 * web app share one typed PaperTrail ABI (viem `as const`). Run `forge build` first.
 */
import { readFileSync, writeFileSync } from "node:fs";

const art = JSON.parse(readFileSync(new URL("../packages/contracts/out/PaperTrail.sol/PaperTrail.json", import.meta.url), "utf8"));
const body = `// GENERATED by scripts/gen-abi.ts from packages/contracts/out/PaperTrail.sol/PaperTrail.json. Do not edit.
export const PAPERTRAIL_ABI = ${JSON.stringify(art.abi, null, 2)} as const;
`;
writeFileSync(new URL("../packages/shared/src/abi.ts", import.meta.url), body);
console.log(`wrote ${art.abi.length} ABI entries`);
